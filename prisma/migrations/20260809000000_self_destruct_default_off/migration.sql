-- createdAt >= cutoff),不删库里的行。默认 2 天意味着用户只翻得到最近两天的聊天
-- 记录,而且没有任何报错或提示 —— 消息只是安静地消失。自毁是隐私功能,应当由
-- 用户主动开启。
