-- 回收站 30 天保留期首次上线的基线:给存量已删行一个完整的宽限窗口。
--
-- 旧契约没有到期清理("已删除的笔记可在这里恢复",无期限),清理任务又按
-- updatedAt 判龄(DELETED 后再无写路径,updatedAt 语义即删除时刻)。不做基线的话,
-- 上线后第一个 4AM 扫描会一次性硬删所有 30 天前软删的存量笔记(NoteMedia 级联)——
-- 用户从未被告知过这个期限。把存量 DELETED 行的时钟重置为部署时刻,等价于
-- "自上线起 30 天后到期",新删除的行不受影响(它们的 updatedAt 本来就是删除时刻)。
UPDATE "Note" SET "updatedAt" = NOW() WHERE "status" = 'DELETED';
